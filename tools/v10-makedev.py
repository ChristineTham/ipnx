#!/usr/bin/env python3
"""Turn a proto-dev into the two guest scripts that repair /dev.

	tools/v10-makedev.py <proto-dev> <part1-out> <part2-out>

TWO PARTS, because the repair spans a reboot.

  part 1, on the live system.  Creates every correct node that is missing --
  the corrected names differ from the wrong ones (ra00 where a generated /dev
  had ra0a), so they go in beside them and nothing in use is disturbed.  Then
  it removes the wrong nodes that are NOT in use.  In use means: named in
  /etc/mtab, or the console.  /etc/mtab is a binary array of
  {char file[32]; char spec[31]; char type;} (fstab.h:42-46), so it is read
  with tr, not grep.

  part 2, after the reboot.  Removes what part 1 protected, which by then is
  running on the new names.

WHY REMOVING A MOUNTED DEVICE'S NODE WOULD ACTUALLY BE SAFE, and why it is
still not done: the kernel holds a mounted filesystem by the inode it looked
up at mount time, and funmount() takes the MOUNT POINT, not the device
(os/mount.c:57-63 -- namei(name) then i_mpoint).  So unmounting does not need
the node.  What does need it is the NEXT boot's /etc/rc.  Deleting it early
buys nothing and costs the ability to boot if a config file was missed.
"""
import sys, os

def main():
    src, out1, out2 = sys.argv[1], sys.argv[2], sys.argv[3]
    nodes, dirs = [], []
    for line in open(src):
        if line.startswith("#") or not line.strip():
            continue
        name, typ, maj, minor, mode = line.split()
        if "/" in name:
            d = name.rsplit("/", 1)[0]
            if d not in dirs:
                dirs.append(d)
        nodes.append((name, typ, int(maj), int(minor), mode))
    dirlist = " ".join(dirs)

    with open(out1, "w") as f:
        w = f.write
        w("# /dev repair, part 1 -- RUN ON THE LIVE SYSTEM\n"
          "# Generated by tools/v10-makedev.py from %s.\n"
          "#\n"
          "# Creates every correct node that is missing, then removes the wrong\n"
          "# ones that are not in use.  A node is in use if /etc/mtab names it or\n"
          "# it is the console.  Nothing in use is touched, and no existing node\n"
          "# is chmodded.\n"
          "MKNOD=/etc/mknod\n"
          "DEV=${1-/dev}\n"
          "test -d $DEV || mkdir $DEV\n" % os.path.basename(src))
        for d in dirs:
            w("test -d $DEV/%s || mkdir $DEV/%s\n" % (d, d))
        w("\necho '--- 1. creating missing nodes ---'\n")
        for name, typ, maj, minor, mode in nodes:
            t = "-c" if typ == "c" else "-b"
            w("test %s $DEV/%s || { echo %s; $MKNOD $DEV/%s %s %d %d; chmod 0%s $DEV/%s; }\n"
              % (t, name, name, name, typ, maj, minor, mode, name))
        w("\necho '--- 2. what should be there ---'\n"
          "rm -f /tmp/dev.ok\n")
        for name, _, _, _, _ in nodes:
            w("echo %s >> /tmp/dev.ok\n" % name)
        w("""
echo '--- 3. what is there now ---'
cd $DEV
ls > /tmp/dev.now
for d in %s
do
	ls $d | sed "s|^|$d/|" >> /tmp/dev.now
done

echo '--- 4. what is IN USE (mtab is binary: fstab.h:42-46) ---'
rm -f /tmp/dev.keep
tr '\\000' '\\012' < /etc/mtab | grep /dev/ | sed 's|^/dev/||' >> /tmp/dev.keep
echo console >> /tmp/dev.keep
cat /tmp/dev.keep

echo '--- 5. wrong AND unused -- removing these ---'
awk 'NR==FNR{ok[$1]=1;next} !ok[$1]' /tmp/dev.ok /tmp/dev.now > /tmp/dev.extra
awk 'NR==FNR{k[$1]=1;next} !k[$1]' /tmp/dev.keep /tmp/dev.extra > /tmp/dev.rm
awk 'NR==FNR{k[$1]=1;next} k[$1]'  /tmp/dev.keep /tmp/dev.extra > /tmp/dev.later
cat /tmp/dev.rm
sh -c 'cd '$DEV'; while read n; do rm -f $n; done' < /tmp/dev.rm

echo '--- 6. wrong but IN USE -- part 2 removes these after the reboot ---'
cat /tmp/dev.later
cp /tmp/dev.later /etc/dev.later
echo 'saved as /etc/dev.later'
""" % dirlist)

    with open(out2, "w") as f:
        f.write("""# /dev repair, part 2 -- RUN AFTER THE REBOOT
# Removes the wrong nodes part 1 could not touch because they were in use.
# Run this only once the machine has come up on the new names.
DEV=${1-/dev}
test -s /etc/dev.later || { echo 'nothing left over'; exit 0; }
echo '--- removing what part 1 protected ---'
cat /etc/dev.later
sh -c 'cd '$DEV'; while read n; do rm -f $n; done' < /etc/dev.later
rm -f /etc/dev.later
echo 'done'
""")
    print("%s: %d nodes, %d directories" % (out1, len(nodes), len(dirs)))

main()
