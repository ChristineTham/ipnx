#!/usr/bin/env python3
r"""Every file in v10/source, and what it does.

	tools/v10-files.py            # write docs/v10-files.md

54,328 lines, one per entry, generated from v10/READ.jsonl -- which is the
record of every file having been OPENED AND READ, not sampled and not
classified by suffix.  This exists to be checked: if a file's line is wrong,
the reader is wrong, and that is a far easier thing to notice than a plan that
is quietly short.

WHERE THE ENGLISH COMES FROM.  The tape describes itself.  Every manual page's
`.SH NAME' line is prose written by the people who wrote the program --
`ls, lc \(mi list contents of directory' -- so a source file that builds `ls'
is described by ls's own manual rather than by anything inferred.  Where no
manual exists the line says what the file itself states: what it defines, what
it includes, how many members an archive holds.
"""

import collections
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACTS = os.path.join(ROOT, "v10", "READ.jsonl")
OUT = os.path.join(ROOT, "docs", "v10-files.md")


def load():
    if not os.path.exists(FACTS):
        sys.exit("v10-files: no v10/READ.jsonl -- run tools/v10-read.py")
    return [json.loads(l) for l in open(FACTS)]


def describe(f, bydesc):
    """One line saying what this file does."""
    k = f.get("kind")
    base = os.path.basename(f["path"])
    stem = base.rsplit(".", 1)[0]
    # A UNIT'S ENTRY POINT IS OFTEN main.c, and naming the program after the
    # FILE calls it `main' -- cmd/sh, games/rogue and cmd/pic all keep theirs
    # there.  The program is the DIRECTORY.  This is the same blind spot that
    # once left the shell with no row in the plan at all.
    if stem == "main":
        stem = os.path.basename(os.path.dirname(f["path"])) or "main"

    if k == "manual":
        d = f.get("desc") or ""
        names = ", ".join(f.get("names", [])) or stem
        sec = f.get("section", "?")
        return "manual page %s(%s)%s" % (names, sec, " -- " + d if d else "")
    if k == "source":
        d = bydesc.get(stem) or bydesc.get(os.path.basename(
            os.path.dirname(f["path"])))
        n = len(f.get("defines_fn", []))
        if f.get("main"):
            return ("the %s program%s" % (stem, " -- " + d if d else "")
                    + (" [%d functions]" % n if n else ""))
        if d and n:
            return "part of %s -- %s [%d functions]" % (stem, d, n)
        defs = [x[0] if isinstance(x, list) else x
                for x in f.get("defines_fn", [])][:4]
        return ("source, defines %s%s" % (", ".join(defs) or "no functions",
                                          ", ..." if n > 4 else ""))
    if k == "header":
        n = len(f.get("defines", []))
        inc = [h for b, h in f.get("includes", [])][:3]
        return ("header, %d definitions%s"
                % (n, "; includes " + ", ".join(inc) if inc else ""))
    if k == "buildfile":
        t = [x for x in f.get("targets", []) if not x.startswith(".")][:6]
        return "build file, targets: %s" % (", ".join(t) or "none parsed")
    if k == "archive":
        m = f.get("members", [])
        return ("archive of %d members%s"
                % (len(m), " (" + ", ".join(m[:3]) + " ...)" if m else ""))
    if k == "object":
        t = f.get("text", 0)
        return ("compiled object, %d bytes of text%s"
                % (t, " -- EMPTY, an lcc hazard" if f.get("empty_text") else ""))
    if k == "script":
        return "shell script%s" % (" (%s)" % f["interp"] if f.get("interp") else "")
    if k == "text":
        form = f.get("form", "text")
        first = (f.get("first") or "").strip()[:70]
        names = {"roff": "roff/troff input", "readme": "a README",
                 "termcap": "terminal descriptions", "table": "a data table",
                 "wordlist": "a word or name list", "cfragment": "C fragment",
                 "buildfile": "a build file"}
        return "%s%s" % (names.get(form, "text"),
                         " -- " + first if first else "")
    if k == "empty":
        return "empty (zero bytes)"
    if k == "binary":
        return "binary data, %d bytes" % f.get("size", 0)
    if k == "link-dir":
        return "a symbolic link to a directory (counted, not followed)"
    if k == "broken-link":
        return "a broken symbolic link"
    return k or "?"


def main():
    facts = load()
    bydesc = {}
    for f in facts:
        if f.get("kind") == "manual" and f.get("desc"):
            for n in f.get("names", []):
                bydesc.setdefault(n, f["desc"])

    byroot = collections.defaultdict(list)
    for f in sorted(facts, key=lambda x: x["path"]):
        byroot[f["path"].split("/")[0]].append(f)

    out = ["# Every file on the tape, and what it does\n\n",
           "Generated by `tools/v10-files.py` from `v10/READ.jsonl` — the "
           "record of every entry under `v10/source` having been opened and "
           "read. %s entries.\n\n" % format(len(facts), ","),
           "Descriptions of programs come from the tape's own manual pages; "
           "everything else says what the file itself states.\n\n"]
    kinds = collections.Counter(f.get("kind") for f in facts)
    out.append("| kind | files |\n|---|---:|\n")
    for k, v in kinds.most_common():
        out.append("| %s | %s |\n" % (k, format(v, ",")))
    for root in sorted(byroot):
        fs = byroot[root]
        out.append("\n## %s — %s files\n\n" % (root, format(len(fs), ",")))
        out.append("| file | what it does |\n|---|---|\n")
        for f in fs:
            d = describe(f, bydesc).replace("|", "\\|")
            out.append("| `%s` | %s |\n" % (f["path"], d))
    open(OUT, "w").write("".join(out))
    print("v10-files: %s entries -> docs/v10-files.md (%.1f MB)"
          % (format(len(facts), ","), os.path.getsize(OUT) / 1e6))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
