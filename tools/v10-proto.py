#!/usr/bin/env python3
"""Generate a proto-dev for a kernel, from that kernel's own config.

	tools/v10-proto.py <config.m> [--tab v10/usr/src/sys/lib/tab]

Two inputs and no third: the .m says which devices exist and how many, and
sys/lib/tab says what major each driver got.  Nothing is taken from a disk.

WHY NOT `ls -l /dev' OFF A RUNNING MACHINE, which is how v8/proto-dev was
made.  For V8 the listing IS the evidence -- it is the shipped machine's own
/dev and no other record survives.  For V10 there is no shipped machine:
every /dev we have was generated by us.  The one in git until 300cbdfc said
so in its header -- "majors are seki.c.c's own cdevsw[]/bdevsw[]; the shape
follows the V8 golden" -- and seki is milligan's kernel, not ours.  Checked
against sys/lib/tab it had 64 pt/* nodes on a major our tab does not define
and 95 dk/* nodes on major 31, which our tab calls kdi.  Re-reading that
listing would have recorded all 159 as if they were evidence.

WHICH tab, and it is not the obvious one.  sys/mkconf/tab and sys/lib/tab
disagree exactly here: mkconf/tab comments out `bdev 0 hp' and `cdev 4 hp'
and enables `cdev 18 pt', while lib/tab does the reverse.  lsys/lib/mk.star
line 19 runs `mkconf -t $LD/tab', so lib/tab is the one the kernel is built
from and mkconf/tab is not used.

fields: name<TAB>b|c<TAB>major<TAB>minor<TAB>mode
"""
import re, sys, os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def read_tab(path):
    b, c = {}, {}
    for line in open(path):
        m = re.match(r"^(bdev|cdev)\s+(\d+)\s+(\S+)", line)
        if m:
            (b if m.group(1) == "bdev" else c)[m.group(3)] = int(m.group(2))
    return b, c

def read_conf(path):
    """instances[name] -> list of unit numbers;  counts[name] -> the count."""
    inst, counts = {}, {}
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        f = line.split()
        name = f[0]
        if len(f) >= 2 and f[1].isdigit() and len(f) > 2:
            inst.setdefault(name, []).append(int(f[1]))       # `dz11 0 ub 0 ...'
        elif len(f) == 2 and f[1].isdigit():
            counts[name] = int(f[1])                          # `tcp 96'
        elif len(f) >= 2 and f[1].isdigit():
            inst.setdefault(name, []).append(int(f[1]))
    return inst, counts

PARTS = "abcdefgh"

# v8/proto-dev's own ra modes, keyed by minor
V8RA = {
    0: [("ra00","b",64,0o640), ("ra01","b",1,0o640), ("ra02","b",66,0o640), ("ra03","b",67,0o640), ("ra04","b",68,0o640), ("ra05","b",69,0o640), ("ra06","b",70,0o640), ("rra00","c",0,0o640), ("rra01","c",1,0o640), ("rra02","c",2,0o640), ("rra03","c",3,0o640), ("rra04","c",4,0o640), ("rra05","c",5,0o640), ("rra06","c",6,0o640), ("rra07","c",7,0o640)],
    1: [("ra10","b",72,0o640), ("ra11","b",9,0o640), ("ra12","b",74,0o640), ("ra13","b",75,0o640), ("ra14","b",76,0o640), ("ra15","b",77,0o640), ("ra16","b",78,0o640), ("rra10","c",8,0o660), ("rra11","c",9,0o640), ("rra12","c",10,0o640), ("rra13","c",11,0o640), ("rra14","c",12,0o640), ("rra15","c",13,0o640), ("rra16","c",14,0o660), ("rra17","c",15,0o640)],
    2: [("ra20a","b",80,0o664), ("ra21","b",17,0o640), ("ra22","b",18,0o664), ("ra23","b",83,0o640), ("ra24","b",84,0o640), ("ra25","b",85,0o640), ("ra26","b",22,0o640), ("rra20","c",16,0o640), ("rra21","c",17,0o640), ("rra22","c",18,0o640), ("rra23","c",19,0o640), ("rra24","c",20,0o640), ("rra25","c",21,0o640), ("rra26","c",22,0o640), ("rra27","c",23,0o640)]
}
V8RA_B = {1:0o640, 9:0o640, 17:0o640, 18:0o664, 22:0o640, 64:0o640, 66:0o640, 67:0o640, 68:0o640, 69:0o640, 70:0o640, 72:0o640, 74:0o640, 75:0o640, 76:0o640, 77:0o640, 78:0o640, 80:0o664, 83:0o640, 84:0o640, 85:0o640}
V8RA_C = {0:0o640, 1:0o640, 2:0o640, 3:0o640, 4:0o640, 5:0o640, 6:0o640, 7:0o640, 8:0o660, 9:0o640, 10:0o640, 11:0o640, 12:0o640, 13:0o640, 14:0o660, 15:0o640, 16:0o640, 17:0o640, 18:0o640, 19:0o640, 20:0o640, 21:0o640, 22:0o640, 23:0o640}

def gen(cfg, tabpath):
    b, c = read_tab(tabpath)
    inst, counts = read_conf(cfg)
    out, notes = [], []

    def add(name, typ, drv, minor, mode):
        table = b if typ == "b" else c
        if drv not in table:
            notes.append("%-22s no %sdev for %s in the tab -- skipped"
                         % (name, typ, drv))
            return
        out.append((name, typ, table[drv], minor, mode))

    # console, starcons, fineclock -- one node each, minor 0
    for drv, nm, mode in (("console","console",0o622), ("starcons","starcons",0o622),
                          ("fineclock","fineclock",0o644)):
        if drv in inst or drv in counts:
            add(nm, "c", drv, 0, mode)

    # mem: mem.c switches on minor 0,1,2,3,5
    if "mem" in inst or "mem" in counts:
        # modes are v8/proto-dev's, the shipped machine's own /dev
        for minor, nm, mode in ((0,"mem",0o644), (1,"kmem",0o644), (2,"null",0o666),
                                (3,"kUmem",0o600), (5,"mtpr",0o600)):
            add(nm, "c", "mem", minor, mode)

    # dz11: 8 lines each (devs:77 `rep 8'), minor = controller*8 + line
    for u in sorted(inst.get("dz11", [])):
        for l in range(8):
            add("tty%02d" % (u*8+l), "c", "dz11", u*8+l, 0o622)

    # hp: hp.c:273  UNIT=(minor>>3)&027, PART=minor&07
    for u in sorted(inst.get("hp", [])):
        for p, ch in enumerate(PARTS):
            add("rp%d%s"  % (u, ch), "b", "hp", u*8+p, 0o640)
            add("rrp%d%s" % (u, ch), "c", "hp", u*8+p, 0o640)

    # ra: man4/ra.4 states the whole thing --
    #   "Files with minor device numbers 0 through 7 refer to different
    #    sections of drive 0, minor devices 8 through 16 refer to drive 1,
    #    and so on up to 63 (8 drives)."
    #   "If 64 is added to the minor device number, 4096-byte blocks (4K) are
    #    used instead.  A 4K device mounted as a file system is bitmapped."
    #   "Conventionally the files are given names like ra37 for section 7 of
    #    drive 3.  There are no name rules distinguishing 1024-byte files from
    #    4096-byte files; in practice the files are almost always the
    #    4096-byte kind."
    #   "The names of the raw files begin with rra and end with a number which
    #    selects the same disk as the corresponding ra file."
    #
    # So the name is ra<drive><section> and NOT ra<drive><letter>, which is
    # what this tool emitted before and had no source for.  v8/proto-dev uses
    # the same form.  0100 is the 4K/bitmapped bit, per section: v8 has ra00
    # at 64 and ra02 at 66 but ra01 -- swap, no filesystem -- at 1, and every
    # raw node at 0..23 with the bit clear, because a raw device is not a
    # filesystem either.
    #
    # Units 8..15 are unreachable: ra.c:39's 027 mask clears the shifted bit
    # that 0100 uses, so `ra 8' computes to minor 64 and UNIT() reads it back
    # as 0.  phone/gauss.m, a real config with sixteen drives, jumps 0..7 then
    # 16..23, and mkconf sizes the arrays by max id + 1 (gauss.c.c:275 is
    # radisk[24]).
    # ra: EMIT ONLY THE DRIVES v8/proto-dev COVERS -- 0, 1 and 2 -- and never
    # beyond, at Christine's direction.  man4/ra.4 does give a rule (minor =
    # drive*8 + section, +64 for 4K/bitmapped, named ra<drive><section>, raw
    # rra<same number>), but the only /dev we have from a real machine already
    # departs from it on the third drive: ra22 and ra26 carry no 0100 bit
    # where the same sections of drives 0 and 1 do, and section 0 is named
    # ra20a.  That reads as site configuration, not convention, so a rule
    # extended past drive 2 would be an invention of ours dressed as evidence.
    #
    # For the drives it does cover, v8's nodes are taken VERBATIM -- names,
    # minors and modes -- including that it makes no section-7 node anywhere.
    # raopen (ra.c:102-105) bounds-checks with `if (unit >= racnt) { ENXIO; }',
    # so a node for a drive this kernel does not configure fails cleanly on
    # open rather than indexing past radisk[].
    if inst.get("ra"):
        for u in sorted(V8RA):
            for name, typ, minor, mode in V8RA[u]:
                add(name, typ, "ra", minor, mode)
        beyond = [u for u in sorted(inst["ra"]) if u not in V8RA]
        if beyond:
            notes.append("ra %-19s configured but no nodes emitted: v8/proto-dev "
                         "covers drives 0..2 only, and its third is already "
                         "irregular" % (",".join(str(u) for u in beyond)))

    # te16: te16.c:120-122  TEUNIT=minor&03, H_NOREWIND=04, H_1600BPI=010.
    #
    # THE DIGIT IS THE DENSITY, NOT THE DRIVE, and V10 says so itself --
    # man4/mt.4: "Conventionally rmt0 is 800, rmt1 is 1600, and rmt2 is 6250
    # bpi", with `rmt' rewound on close and `nrmt' not.  v8/proto-dev uses a
    # DIFFERENT scheme (mt1=800 rewind, mt2=1600 rewind, mt5/mt6 the
    # no-rewind pair) and copying it onto V10 gets every name wrong.  mt.4's
    # FILES are /dev/mt?, /dev/rmt?, /dev/nmt?, /dev/nrmt?.
    #
    # rmt2 does not exist here: 6250 bpi is a TU78/TM78, and te16.c has bits
    # for 800 and 1600 only.  mt.4's own BUGS note says the convention
    # "behaves poorly with multiple tape drives" -- with one te16 the four
    # names are unambiguous, which is what we configure.
    #
    # Modes are v8/proto-dev's for the same ROLES (its 800-rewind node is
    # 666, so ours is), because neither mt.4 nor the driver states a mode and
    # v8's shipped /dev is the only evidence there is.
    for u in sorted(inst.get("te16", [])):
        for dens, bit in ((0, 0), (1, 0o10)):          # 0 = 800bpi, 1 = 1600bpi
            add("mt%d"   % dens, "b", "te16", u | bit,      0o666)
            add("rmt%d"  % dens, "c", "te16", u | bit,      0o666)
            add("nmt%d"  % dens, "b", "te16", u | bit | 4,  0o666)
            add("nrmt%d" % dens, "c", "te16", u | bit | 4,  0o666)

    # ta (TU81), one node pair per unit
    for u in sorted(inst.get("ta", [])):
        add("ta%d"  % u, "b", "ta", u, 0o640)
        add("rta%d" % u, "c", "ta", u, 0o640)

    # drum / swap
    if "drum" in inst or "drum" in counts:
        add("drum", "c", "drum", 0, 0o644)      # v8/proto-dev
        add("swap", "b", "drum", 0, 0o640)

    # stdio: fd.c -- "open(minor n) -> dup of minor n", NOFILE 128
    if "stdio" in inst or "stdio" in counts:
        # /dev/tty IS 40,3, and it is a real controlling terminal -- but by a
        # USERLAND CONVENTION, not a kernel special case, which is why no
        # driver appears to implement it.  param.h:9 states it outright:
        #
        #	#define NSYSFILE 4	/* stdin, stdout, stderr, /dev/tty */
        #
        # init.c's setupio() opens the tty and then calls dup(0) THREE times,
        # not twice, so the terminal sits on fds 0,1,2 AND 3 and is inherited
        # by everything; login.c:56 closes only `for (i=NSYSFILE; i<NOFILE;
        # i++)', preserving it.  fd.c is then exactly right: opening 40,3 in a
        # process that inherited fd 3 lands on fd 4, so ofd != minor and the
        # driver dups fd 3 -- the terminal.  It fails only in a process that
        # closed fd 3, which is the same condition under which a controlling
        # terminal is gone anyway.
        #
        # v8/proto-dev carries stdin/fd/0, stdout/fd/1, stderr/fd/2, tty/fd/3
        # as HARD LINKS with link count 2; v8's makedev.sh:249-296 reproduces
        # them as separate mknods of the same major/minor, which is
        # functionally identical.  Same here.
        for minor, nm in ((0,"stdin"), (1,"stdout"), (2,"stderr"), (3,"tty")):
            add(nm, "c", "stdio", minor, 0o666)
        for n in range(128):
            add("fd/%d" % n, "c", "stdio", n, 0o666)

    # kdi: kdi.c:140-142  KDICHAN 96 per kmc, KMC(d)=d/96, CHAN(d)=d%96
    # kdi is DK.  kdi.c:1-2 is "stream driver for DK via KMC-11/KDI board",
    # so major 31 is the same device V8 had there -- V10 names the driver after
    # the board.  The nodes are /dev/dk/*, which is what V10's own userland
    # opens; no /dev/kdi* string exists anywhere in the tree.
    #
    # NAMES are stated by dkmgr(8): "/dev/dk/dknn with nn a two-digit channel
    # number.  If there are more than 100 channels, the first digit overflows
    # to lower-case letters: channel 100 is a0.  The common signaling control
    # channel is named /dev/dk/dkctl."  tdkdial.c:76,91 builds exactly that
    # from alph[] = "0123456789abcdefghijklmnopqrstuvwxyz".  man4/dk.4: "the
    # device number is the channel number", 96 per KMC pair (kdi.c:140).
    #
    # ROLES, and each mode follows one:
    #   dkctl / channel 1  the common signaling channel.  dkctlchan.c opens
    #                      dk01 first and falls back to the name dkctl, so the
    #                      two are the same channel.  600: dkhup(8) runs it.
    #   even               login lines.  v8/etc/ttys lists dk02..dk94 -- every
    #                      even channel -- as getty lines, so they are ttys and
    #                      take a tty's 622.
    #   odd                dial-out.  tdkdial.c:82 scans `for (i=3; i<256;
    #                      i+=2)', odd only.  666.
    #
    # v8/proto-dev's odd channels are 666 up to 49 and 664 from 51, which is
    # NOT a rule: the 664 bank is group bin, and twelve of them carry the
    # /dev/dk directory's own mtime of Sep 13 1984 -- one batch of nodes made
    # later and never used since, where 3..49 are group sys with 1985 mtimes.
    # No V8 or V10 source defines a boundary at 50.  It is two years of
    # accretion on a live machine, not something to reproduce on a fresh one.
    # MODES ARE v8/proto-dev's, VERBATIM.  Christine's call: the rule this
    # tool derived (control 600, odd 666, even 622) matched 65 of 95 and could
    # not account for the rest, so the shipped machine's own listing is taken
    # as authoritative instead of a rule of ours.  v8 covers channels 1..95,
    # one KMC; past that the same channel modulo 96 is used, which is the only
    # part not backed by the listing.
    if "kdi" in counts:
        alph = "0123456789abcdefghijklmnopqrstuvwxyz"
        V8DK = {1:0o600, 2:0o622, 3:0o666, 4:0o622, 5:0o666, 6:0o644, 7:0o666, 8:0o622, 9:0o666, 10:0o644, 11:0o666, 12:0o622, 13:0o666, 14:0o622, 15:0o666, 16:0o622, 17:0o666, 18:0o622, 19:0o666, 20:0o622, 21:0o666, 22:0o722, 23:0o666, 24:0o622, 25:0o666, 26:0o622, 27:0o666, 28:0o622, 29:0o666, 30:0o622, 31:0o666, 32:0o722, 33:0o666, 34:0o622, 35:0o666, 36:0o622, 37:0o666, 38:0o622, 39:0o666, 40:0o622, 41:0o666, 42:0o622, 43:0o666, 44:0o622, 45:0o666, 46:0o622, 47:0o666, 48:0o622, 49:0o666, 50:0o622, 51:0o664, 52:0o622, 53:0o664, 54:0o622, 55:0o664, 56:0o622, 57:0o664, 58:0o644, 59:0o664, 60:0o622, 61:0o664, 62:0o622, 63:0o664, 64:0o622, 65:0o664, 66:0o722, 67:0o664, 68:0o622, 69:0o664, 70:0o622, 71:0o664, 72:0o622, 73:0o664, 74:0o622, 75:0o664, 76:0o622, 77:0o664, 78:0o622, 79:0o664, 80:0o622, 81:0o664, 82:0o622, 83:0o664, 84:0o622, 85:0o664, 86:0o622, 87:0o664, 88:0o622, 89:0o664, 90:0o622, 91:0o664, 92:0o644, 93:0o664, 94:0o622, 95:0o664}
        add("dk/dkctl", "c", "kdi", 1, V8DK[1])
        for ch in range(1, counts["kdi"] * 96):
            mode = V8DK.get(ch, V8DK.get(ch % 96, 0o622))
            add("dk/dk%c%d" % (alph[ch // 10], ch % 10), "c", "kdi", ch, mode)

    for u in sorted(inst.get("kmc11b", [])):
        add("kmc%d" % u, "c", "kmc11b", u, 0o666)
    # dn11: the 0200 bit is FUNCTIONAL, not decoration.  dn.c:91-93 sets
    # ldlo = DLO when it is present, which makes data-line-occupied a
    # terminating condition in the dial loop; dn.c:94 then masks it off for
    # the unit.  v8/proto-dev ships dn0 at minor 128 = 0200|0, so that is the
    # behaviour the shipped machine chose, and minor 0 would differ silently.
    for u in sorted(inst.get("dn11", [])):
        add("dn%d" % u, "c", "dn11", 0o200 | u, 0o666)
    # ni1010a: EIGHT minors per board.  ni1010a.c:3 -- "Each hardware device
    # has eight minor devices starting at N*8" -- and :130-135 decodes
    # unit = minor/NILCHAN, chan = minor%NILCHAN, with NILCHAN 8
    # (ni1010a.h:11).  One node per unit is wrong: /etc/rc passes /dev/il1 to
    # dipconfig as its ARP channel (dipconfig.c:33, argv[4]).
    for u in sorted(inst.get("ni1010a", [])):
        for ch in range(8):
            n = u * 8 + ch
            add("il%d" % n, "c", "ni1010a", n, 0o600 if ch == 0 else 0o666)
    for u in sorted(inst.get("drbit", [])):
        add("dr%d" % u, "c", "drbit", u, 0o600)

    # tcp/udp: the minor IS bounded by the config -- tcp_device.c:43 and
    # udp_device.c:39 both `if(dev >= Ncnt) return(0)'.  tcp_lib.c:17 builds
    # the name as "/dev/tcp%02d", so that spelling is the tape's, not ours.
    # tcp modes ALTERNATE, and it is not decoration: tcp_device.c:43 is
    # `if(dev&01){ /* outgoing channel */', so an ODD minor is the channel a
    # user program opens to make a connection and an EVEN one is incoming,
    # for the listener alone.  v8/proto-dev has exactly that -- tcp00 600,
    # tcp01 666, tcp02 600, tcp03 666, all twelve of them.
    for n in range(counts.get("tcp", 0)):
        add("tcp%02d" % n, "c", "tcp", n, 0o666 if n & 1 else 0o600)
    for n in range(counts.get("udp", 0)):
        add("udp%02d" % n, "c", "udp", n, 0o666)

    # ip: the minor is the IP PROTOCOL NUMBER, not an index.  ip_device.c:30
    # indexes `struct queue *ipdstate[256]' with no bound, and the config's
    # `ip N' counts ipif interfaces (devs:65), not minors -- so generating
    # ip00..ip0(N-1) from the count, which is what this tool did first, gives
    # nodes nothing opens and omits every one that something does.  Each of
    # these is named by a caller in the tape:
    #     ip0      route.c:47                      raw
    #     ipicmp   icmpmgr.c:295                   1, ICMP
    #     ip6      linedis.c:14 "tcp_ld ... on /dev/ip6"
    #     iptcp    tcpmgr/main.c:93 IPDEVFORTCP    6, TCP -- same minor as ip6
    #     ip16     routed.c:11 IPDEVICE
    #     ip17     17, UDP -- v8/proto-dev has it; no V10 caller names it
    if "ip" in counts or "ip" in inst:
        for nm, minor in (("ip0",0), ("ipicmp",1), ("ip6",6), ("iptcp",6),
                          ("ip16",16), ("ip17",17)):
            add(nm, "c", "ip", minor, 0o666)

    # pt: the STREAM PIPE device, not pseudo-ttys.  v8's cdevsw shows major 18
    # is spinfo (v8/usr/sys/dev/spipe.c) and V10 ships the same driver as
    # lsys/io/spipe.c; PATCHES.md:289 records why our tab uncomments
    # `cdev 18 pt'.  So whether these exist depends on WHICH tab the kernel
    # was built from -- the tape's has the line commented out with its own
    # "# remove?".
    if "pt" in counts:
        if "pt" in c:
            for n in range(counts["pt"]):
                add("pt/pt%02d" % n, "c", "pt", n, 0o666)
        else:
            notes.append("%-22s `pt %d' is configured but this tab has no cdev 18 "
                         "-- no nodes" % ("pt", counts["pt"]))
    return out, notes

def main():
    cfg = sys.argv[1]
    tab = sys.argv[3] if len(sys.argv) > 3 else os.path.join(REPO, "v10/usr/src/sys/lib/tab")
    out, notes = gen(cfg, tab)
    print("# The Tenth Edition /dev for %s." % os.path.basename(cfg))
    print("#")
    print("# Generated by tools/v10-proto.py from that config and sys/lib/tab.")
    print("# Nothing here is read off a disk: every /dev image we have was")
    print("# generated by us, so a listing is not evidence.  See the tool.")
    print("#")
    print("# fields: name<TAB>b|c<TAB>major<TAB>minor<TAB>mode")
    print("#")
    for n in notes:
        print("# NOTE: %s" % n)
    if notes:
        print("#")
    for name, typ, maj, minor, mode in out:
        print("%s\t%s\t%d\t%d\t%o" % (name, typ, maj, minor, mode))

main()
