C     ELEMENT (11) SHOULD EQUAL '-+'   ....
      IF ( IACN12(16) .EQ. IADN12(16) )  IVON01 = IVON01 + 1
C     ELEMENT (16) SHOULD EQUAL 'TS'   ....
