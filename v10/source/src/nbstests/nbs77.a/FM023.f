      WRITE (I02,90004)
      WRITE (I02,90002)
      WRITE (I02,90011)
      WRITE (I02,90002)
      WRITE (I02,90002)
      WRITE (I02,90005)
      WRITE (I02,90006)
      WRITE (I02,90002)
      IVTNUM = 632
C
C      ****  TEST 632  ****
C     TEST 632  -  TESTS SETTING AN INTEGER ARRAY ELEMENT BY A
C     SIMPLE ASSIGNMENT STATEMENT TO THE VALUE 9999.
C
      IF (ICZERO) 36320, 6320, 36320
 6320 CONTINUE
      IADN21(1,1) = 9999
      IVCOMP = IADN21(1,1)
      GO TO 46320
36320 IVDELE = IVDELE + 1
      WRITE (I02,80003) IVTNUM
