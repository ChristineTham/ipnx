46400 IF ( IVCOMP - 512 )  26400, 16400, 26400
16400 IVPASS = IVPASS + 1
      WRITE (I02,80001) IVTNUM
      GO TO 6411
26400 IVFAIL = IVFAIL + 1
      IVCORR = 512
      WRITE (I02,80004) IVTNUM, IVCOMP ,IVCORR
 6411 CONTINUE
