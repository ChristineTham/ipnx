C
C
C      REFERENCES
C        AMERICAN NATIONAL STANDARD PROGRAMMING LANGUAGE FORTRAN,
C              X3.9-1978
C
C        SECTION 8, SPECIFICATION STATEMENTS
C        SECTION 8.1, DIMENSION STATEMENT
C        SECTION 8.2, EQUIVALENCE STATEMENT
