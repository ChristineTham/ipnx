      IVCOMP = RADE23(2,2)
      GO TO 46410
36410 IVDELE = IVDELE + 1
      WRITE (I02,80003) IVTNUM
      IF (ICZERO) 46410, 6421, 46410
46410 IF ( IVCOMP - 512 )  26410, 16410, 26410
16410 IVPASS = IVPASS + 1
      WRITE (I02,80001) IVTNUM
      GO TO 6421
26410 IVFAIL = IVFAIL + 1
