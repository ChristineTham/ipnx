10130 IVPASS = IVPASS + 1
      WRITE (I02,80002) IVTNUM
      GO TO 0141
20130 IVFAIL = IVFAIL + 1
      WRITE (I02,80012) IVTNUM, RVCOMP, RVCORR
 0141 CONTINUE
