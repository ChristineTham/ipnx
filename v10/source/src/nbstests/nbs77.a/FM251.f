      VVIN01 = 4
      RVCOMP = VVIN01/5
      RVCORR = 0.0
40130 IF ( RVCOMP )  20130, 10130, 20130
30130 IVDELE = IVDELE + 1
      WRITE (I02,80000) IVTNUM
