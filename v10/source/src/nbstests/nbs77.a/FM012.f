      IF (ICZERO) 41110, 1121, 41110
41110 IF(IVON01-10)  21110, 11110, 21110
11110 IVPASS = IVPASS + 1
      WRITE (I02,80001) IVTNUM
      GO TO 1121
21110 IVFAIL = IVFAIL + 1
      IVCOMP=IVON01
      IVCORR=10
