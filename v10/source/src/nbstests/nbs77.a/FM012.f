      IF (ICZERO) 31120, 1120, 31120
 1120 CONTINUE
      IVON01=0
      DO 1122 K = 1, 10, 2
      IVON01=IVON01+1
 1122 CONTINUE
      GO TO 41120
31120 IVDELE = IVDELE + 1
      WRITE (I02,80003) IVTNUM
      IF (ICZERO) 41120, 1131, 41120
41120 IF (IVON01 - 5 )  21120, 11120, 21120
11120 IVPASS = IVPASS + 1
