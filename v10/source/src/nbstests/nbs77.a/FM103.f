C         THIS ROUTINE IS A TEST OF THE X FORMAT AND IS TAPE AND PRINTER
C     ORIENTED.  THE ROUTINE CAN ALSO BE USED FOR DISK.  BOTH THE READ
C     AND WRITE STATEMENTS ARE TESTED.  VARIABLES IN THE INPUT AND
