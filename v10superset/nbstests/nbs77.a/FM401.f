C          (3) THE VALUES .T, .F,   T,    F, .TRUE., .FALSE.,   .T, AND
C                 .F ARE ACCEPTABLE FORMS FOR INPUT DATA FIELDS
C          (4) THE INPUT VALUES T OR F MAY BE FOLLOWED BY
C              ADDITIONAL CHARACTERS IN THE FIELD,
