C
C        THIS ROUTINE TESTS FOR PROPER EDITING OF LOGICAL DATA BY
C     THE L EDIT DESCRIPTOR OF THE FORMAT SPECIFICATION.  THE L EDIT
C     DESCRIPTOR IS FIRST TESTED FOR PROPER EDITING ON OUTPUT BY
